module annulus_class
    use matrix_glueball_3d_parameters
    use linalg, only: trace
    use lattice, only: periodic, site_index, site_coordinates, move

    implicit none

    public :: annulus

    type annulus
        ! Annulus covers radii r in range r_0 - delta_r <= r <= r_0 + delta_r
        real :: r_0, delta_r

        ! Number of points in annulus defined by r_0, delta_r
        integer :: num_points

        ! Site indices of points in annulus defined by r_0, delta_r, in ascending order of angle from the poisitve x-axis facing anti-clockwise, for every point on the lattice
        integer, allocatable :: points(:,:)

        ! Angles of sites in points array from the x-axis facing anti-clockwise
        real, allocatable :: angles(:)

        contains

        ! Initialise instance of ring class
        procedure :: init=>init_annulus

        ! Find number of points in annulus
        procedure :: get_number_of_points_in_annulus

        ! Get indices of all sites in annulus and angles they make with the +ve x-axis
        procedure :: get_points_in_annulus

        ! Measure all line operators in a given annulus class and sum over sites
        procedure :: measure_lines

        ! Recover number of points in annulus
        procedure :: get_num_points

        ! Recover angles in annulus
        procedure :: get_angles

        ! Calculate sum of phases generated by angles
        procedure :: phase_sum
    end type

    contains

    ! Iniliatlise annulus, points and angles arrays
    subroutine init_annulus(ring, r_0, delta_r)
        class(annulus), intent(inout) :: ring
        real, intent(in) :: r_0, delta_r

        ! Set r_0 and delta_r
        ring%r_0 = r_0
        ring%delta_r = delta_r

        ! Get number of points in annulus defined by r_0 and delta_r
        call ring%get_number_of_points_in_annulus()

        ! Allocate points and angles arrays
        allocate(ring%points(ring%num_points, SLICE_VOLUME), ring%angles(ring%num_points))

        ! Fill points and angles arrays
        call ring%get_points_in_annulus()
    end subroutine

    ! Find number of lattice points in the annulus of radii [r_0 - delta_r, r_0 + delta_r] by finding the number of points in the annulus from site (0,0) in the first quadrant (including y=0 and exluding x=0) and multiplying by 4
    subroutine get_number_of_points_in_annulus(ring)
        implicit none
        class(annulus), intent(inout) :: ring

        integer :: coordinates(2), x, y, site
        real :: r

        ring%num_points = 0
        do site = 1, SLICE_VOLUME
            ! Get coordinates of site in range (-LS/2, LS/2]
            coordinates = site_coordinates(site)
            if (coordinates(1) <= LS/2) then
                x = coordinates(1)
            else
                x = coordinates(1) - LS
            endif
            if (coordinates(2) <= LS/2) then
                y = coordinates(2)
            else
                y = coordinates(2) - LS
            endif

            ! Select for points in the first annulus
            if (x <= 0) cycle
            if (y < 0) cycle

            ! Determine if site falls within annulus, and if so increment counter
            r = sqrt(real(x**2) + real(y**2))
            if ((r >= ring%r_0 - ring%delta_r).and.(r <= ring%r_0 + ring%delta_r)) &
            ring%num_points = ring%num_points + 1
        enddo

        ring%num_points = 4 * ring%num_points
    end subroutine

    ! Get the site indices of all the sites in a given annulus
    subroutine get_points_in_annulus(ring)
        implicit none
        class(annulus), intent(inout) :: ring

        integer :: coordinates(2), x, y, site, i, j, key_point, centre, rotated_coordinates(2)
        real :: r, key_angle

        ! Add points in the annulus in the first quadrant (including y=0 and excluding x=0) from site (0,0) to array, along with angle they make with the x-axis
        i = 0
        do site = 1, SLICE_VOLUME
            ! Get coordinates of site in range (-LS/2, LS/2]
            coordinates = site_coordinates(site)
            if (coordinates(1) <= LS/2) then
                x = coordinates(1)
            else
                x = coordinates(1) - LS
            endif
            if (coordinates(2) <= LS/2) then
                y = coordinates(2)
            else
                y = coordinates(2) - LS
            endif

            ! Select for points in the first annulus
            if (x <= 0) cycle
            if (y < 0) cycle

            ! Determine if site falls within annulus
            r = sqrt(real(x**2) + real(y**2))
            if ((r >= ring%r_0 - ring%delta_r).and.(r <= ring%r_0 + ring%delta_r)) then
                ! Increment counter used for array access
                i = i + 1

                ! Check we have not found more points than we should have
                if (i > ring%num_points/4) error stop &
                "More points found in get_points_in_annulus than in get_number_of_points_in_annulus"

                ! Add site to points array
                ring%points(i, SLICE_VOLUME) = site

                ! Calculate angle and add to angles array
                ring%angles(i) = atan(real(y) / real(x))
            endif
        enddo

        ! Use insertion sort to sort points and angles in order of ascending angle
        do i = 2, ring%num_points/4
            key_point = ring%points(i, SLICE_VOLUME)
            key_angle = ring%angles(i)
            j = i - 1

            ! Move elements of points and angles, for elements where angles is greater than the key, to one position ahead of their current position
            do while (j > 0 .and. key_angle < ring%angles(j))
                ring%points(j+1, SLICE_VOLUME) = ring%points(j, SLICE_VOLUME)
                ring%angles(j+1) = ring%angles(j)
                j = j - 1
            enddo
            ring%points(j+1, SLICE_VOLUME) = key_point
            ring%angles(j+1) = key_angle
        enddo

        ! Use lattice symmetries to get points and angles in other quadrants
        do i = 1, ring%num_points/4
            coordinates = site_coordinates(ring%points(i, SLICE_VOLUME))

            ! Rotate by 90 degrees
            rotated_coordinates(1) = periodic(-coordinates(2))
            rotated_coordinates(2) = periodic(coordinates(1))
            ring%points(ring%num_points/4 + i, SLICE_VOLUME) = site_index(rotated_coordinates)
            ring%angles(ring%num_points/4 + i) = ring%angles(i) + real(PI, kind=real32)/2

            ! Rotate by 180 degrees
            rotated_coordinates = periodic(-coordinates)
            ring%points(ring%num_points/2 + i, SLICE_VOLUME) = site_index(rotated_coordinates)
            ring%angles(ring%num_points/2 + i) = ring%angles(i) + real(PI, kind=real32)

            ! Rotate by 270 degrees
            rotated_coordinates(1) = periodic(coordinates(2))
            rotated_coordinates(2) = periodic(-coordinates(1))
            ring%points(3*ring%num_points/4 + i, SLICE_VOLUME) = site_index(rotated_coordinates)
            ring%angles(3*ring%num_points/4 + i) = ring%angles(i) + 3*real(PI, kind=real32)/2
        enddo

        ! Translate points around the lattice to get points from all other sites on the lattice
        do y = 1, LS
            do x = 1, LS
                ! Do not need to copy data for site = (0,0) ~ (LS,LS)
                if (x == LS .and. y == LS) cycle

                ! Move centre point by (x, y) units
                centre = move(move(SLICE_VOLUME, 1, x), 2, y)

                ! Move all other points by (x, y) units
                do i = 1, ring%num_points
                    ring%points(i, centre) = move(move(ring%points(i, SLICE_VOLUME), 1, x), 2, y)
                enddo
            enddo
        enddo
    end subroutine

    ! Measure all line operators on a given configuration in a given annulus class and sum over sites
    function measure_lines(ring, M_inv) result(lines)
        implicit none
        class(annulus), intent(inout) :: ring
        complex :: M_inv(NCOL, NCOL, SLICE_VOLUME, SLICE_VOLUME)
        complex(8) :: lines(ring%num_points/2)

        integer :: centre, sites(2), line

        ! Measure lines by connecting antipodal points
        ! Conduct zero-momentum sum over sites
        lines = cmplx(0.0,0.0)
        do line = 1, ring%num_points/2
            do centre = 1, SLICE_VOLUME
                sites(1) = ring%points(line, centre)
                sites(2) = ring%points(line + ring%num_points/2, centre)
                lines(line) = lines(line) &
                + trace(matmul(M_inv(:,:,sites(1),sites(2)), M_inv(:,:,sites(2),sites(1))))
            enddo
        enddo
    end function

    ! Recover number of points in annulus
    function get_num_points(ring)
        implicit none
        class(annulus), intent(inout) :: ring
        integer :: get_num_points

        get_num_points = ring%num_points
    end function

    ! Recover angles of points in annulus
    function get_angles(ring)
        implicit none
        class(annulus), intent(inout) :: ring
        real, allocatable :: get_angles(:)

        allocate(get_angles(ring%num_points))
        get_angles = ring%angles
    end function

    ! Calculate phase sum \sum_\theta e^{iJ\theta} over all points in annulus
    function phase_sum(ring, spin)
        implicit none
        class(annulus), intent(inout) :: ring
        integer, intent(in) :: spin
        real :: phase_sum

        integer :: i

        ! Use reflection symmetry of the lattice to calculate sum. This ensures the sum is always real.
        phase_sum = 0.0
        do i = 1, ring%num_points/2
            ! Sum only over angles [0, pi)
            phase_sum = phase_sum + 2.0 * cos(spin * ring%angles(i))
        enddo
    end function
end module